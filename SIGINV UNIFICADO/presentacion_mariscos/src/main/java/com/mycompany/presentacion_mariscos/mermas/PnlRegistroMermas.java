    private void configurarTabla(){
        String[] columnas ={"Insumo", "Stock", "Categoria"};
        DefaultTableModel modelo = new DefaultTableModel(columnas, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // nadie puede editar las celdas
            }
        };
        
        tblInsumos.setModel(modelo);
    }
    
    private int paginaActual = 0;
    private final int REGISTROS_POR_PAGINA = 5;

    private void cargarInsumos() {
        try {
            listaInventario = inventarioControl.obtenerTodos();
            cargarPagina(paginaActual);

            // Clic en fila para rellenar los campos
            tblInsumos.addMouseListener(new java.awt.event.MouseAdapter() {
                @Override
                public void mouseClicked(java.awt.event.MouseEvent evt) {
                    int fila = tblInsumos.getSelectedRow();
                    if (fila >= 0) {
                        // Calcular índice real segun pagina actual
                        int indiceReal = paginaActual * REGISTROS_POR_PAGINA + fila;
                        Inventario inventario = listaInventario.get(indiceReal);

                        txtInsumo.setText(inventario.getInsumo().getNombre());
                        txtUnidadMedida.setText(inventario.getInsumo().getUnidadMedida());
                    }
                }
            });

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar insumos: " + e.getMessage());
        }
    }

    private void cargarPagina(int pagina) {
        DefaultTableModel modelo = (DefaultTableModel) tblInsumos.getModel();
        modelo.setRowCount(0);

        int inicio = pagina * REGISTROS_POR_PAGINA;
        int fin = Math.min(inicio + REGISTROS_POR_PAGINA, listaInventario.size());

        for (int i = inicio; i < fin; i++) {
            Inventario inv = listaInventario.get(i);
            modelo.addRow(new Object[]{
                inv.getInsumo().getNombre(),
                inv.getStockActual(),
                inv.getInsumo().getCategoria()
            });
        }

        int totalPaginas = (int) Math.ceil((double) listaInventario.size() / REGISTROS_POR_PAGINA);
        lblPagina.setText("Página " + (pagina + 1) + " de " + totalPaginas);
    }
    
    private void leerQR(File archivo) {
        try {
            BufferedImage imagen = ImageIO.read(archivo);
            LuminanceSource source = new BufferedImageLuminanceSource(imagen);
            BinaryBitmap bitmap = new BinaryBitmap(new HybridBinarizer(source));

            Result result = new MultiFormatReader().decode(bitmap);
            String contenidoQR = result.getText(); // el nombre del insumo puesto en el metodo generarQR

            // buscar el insumo por el contenido del QR
            Insumo insumo = insumoControl.obtenerInsumoPorNombre(contenidoQR);

            // rellenar campos
            txtInsumo.setText(insumo.getNombre());
            txtUnidadMedida.setText(insumo.getUnidadMedida());

        } catch (NotFoundException e) {
            JOptionPane.showMessageDialog(this, "No se encontro ningun QR en la imagen");
        } catch (Exception e) {
            
            JOptionPane.showMessageDialog(this, "Error al leer QR: " + e.getMessage());
        }
    }
    
    //Filtro para txtCantPerdida para que solo acepte numeros enteros y decimales
    class MyDecimalFilter extends javax.swing.text.DocumentFilter {
        private static final String REGEX = "^[0-9]*\\.?[0-9]*$";

        @Override
        public void insertString(FilterBypass fb, int offset, String string, javax.swing.text.AttributeSet attr) 
                throws javax.swing.text.BadLocationException {
            String currentText = fb.getDocument().getText(0, fb.getDocument().getLength());
            String nextText = currentText.substring(0, offset) + string + currentText.substring(offset);
            if (nextText.matches(REGEX)) { super.insertString(fb, offset, string, attr); }
        }

        @Override
        public void replace(FilterBypass fb, int offset, int length, String text, javax.swing.text.AttributeSet attrs) 
                throws javax.swing.text.BadLocationException {
            String currentText = fb.getDocument().getText(0, fb.getDocument().getLength());
            String nextText = currentText.substring(0, offset) + text + currentText.substring(offset + length);
            if (nextText.matches(REGEX)) { super.replace(fb, offset, length, text, attrs); }
        }
    }

    

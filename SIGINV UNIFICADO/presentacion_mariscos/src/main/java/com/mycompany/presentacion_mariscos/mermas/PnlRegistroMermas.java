    private void btnRegistrarMermaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarMermaActionPerformed
        try{
            
            String nombre = txtInsumo.getText();
            
//            Insumo insumo = insumoControl.obtenerInsumoPorNombre(nombre);
//            String id = insumo.getId().toHexString();
            
            double cantPerdida = Double.parseDouble(txtCantPerdida.getText());
            String unidadMedida = txtUnidadMedida.getText();
            String causaMerma = comboCausa.getSelectedItem().toString();
            String descripcion = txtDescripcion.getText();
            
            //Obtener fecha tipo date por JCalendar
            Date fecha = chooserFecha.getDate();
            
            // validar fecha
            if (chooserFecha.getDate() == null) {
                JOptionPane.showMessageDialog(this, "Seleccione una fecha");
                return;
            }
        
            //Convertir Date a LocalDateTime
            LocalDateTime fechaLocal = fecha.toInstant()
                .atZone(ZoneId.systemDefault())
                .toLocalDateTime();
            
            String ubicacion = comboUbicacion.getSelectedItem().toString();
            
            MermaDTO mermaDTO = new MermaDTO(null, nombre, cantPerdida, unidadMedida, causaMerma, descripcion, ubicacion, fechaLocal);
            
            mermaControl.crearMerma(mermaDTO);
            JOptionPane.showMessageDialog(this, "Merma registrada correctamente!");

                    
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "La cantidad debe ser un número válido");
        }catch(Exception e){
            JOptionPane.showMessageDialog(this, "Error al registrar merma: " + e.getMessage());

        }
        
    }//GEN-LAST:event_btnRegistrarMermaActionPerformed

    private void btnSiguienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSiguienteActionPerformed
        int totalPaginas = (int) Math.ceil((double) listaInventario.size() / REGISTROS_POR_PAGINA);
        if (paginaActual < totalPaginas - 1) {
            paginaActual++;
            cargarPagina(paginaActual);
        }
    }//GEN-LAST:event_btnSiguienteActionPerformed

